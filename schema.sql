-- Nümunə sxem. Mövcud layihədə cədvəllər varsa, təkrar işlətmə.
create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 display_name text, bio text, game_style text, game_uid text,
 updated_at timestamptz default now()
);
create table if not exists public.conversations (
 id uuid primary key default gen_random_uuid(), kind text not null default 'direct',
 title text, direct_key text unique, created_by uuid references auth.users(id) on delete set null,
 created_at timestamptz default now()
);
create table if not exists public.conversation_members (
 conversation_id uuid references public.conversations(id) on delete cascade,
 user_id uuid references auth.users(id) on delete cascade, joined_at timestamptz default now(),
 primary key(conversation_id,user_id)
);
create table if not exists public.messages (
 id bigint generated by default as identity primary key,
 conversation_id uuid not null references public.conversations(id) on delete cascade,
 sender_id uuid not null references auth.users(id) on delete cascade,
 body text not null check(char_length(body) between 1 and 2000), created_at timestamptz default now()
);
create table if not exists public.blocks (
 blocker_id uuid references auth.users(id) on delete cascade,
 blocked_id uuid references auth.users(id) on delete cascade, created_at timestamptz default now(),
 primary key(blocker_id,blocked_id), check(blocker_id<>blocked_id)
);
create table if not exists public.reports (
 id bigint generated by default as identity primary key,
 reporter_id uuid references auth.users(id) on delete cascade,
 reported_user_id uuid references auth.users(id) on delete cascade,
 reason text not null, status text not null default 'pending', created_at timestamptz default now()
);
alter table public.profiles enable row level security;
